#!/bin/bash
# WebAssembly-only clang + lld for iOS arm64, size first, built to run inside the app (see ios-prefix.h, patch.py).
# Usage: configure.sh SRC BUILD iphoneos|iphonesimulator IOS_SYSTEM_XCFRAMEWORK
set -euo pipefail
SRC=$1; BUILD=$2; PLATFORM=$3; IOS_SYSTEM=$4
HERE=$(cd "$(dirname "$0")" && pwd)
SDK=$(xcrun --sdk "$PLATFORM" --show-sdk-path)
case "$PLATFORM" in
    iphoneos) SLICE=ios-arm64;;
    iphonesimulator) SLICE=ios-arm64_x86_64-simulator;;
esac
# Source paths in the binary without the build machine's folders.
FLAGS="-ffunction-sections -fdata-sections -include $HERE/ios-prefix.h -ffile-prefix-map=$SRC=. -ffile-prefix-map=$BUILD=."
LINK="-Wl,-dead_strip -F$IOS_SYSTEM/$SLICE -framework ios_system"
cmake -G Ninja -S "$SRC/llvm" -B "$BUILD" \
  -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_ARCHITECTURES=arm64 -DCMAKE_OSX_SYSROOT="$SDK" \
  -DCMAKE_OSX_DEPLOYMENT_TARGET=17.0 \
  -DCMAKE_BUILD_TYPE=MinSizeRel -DLLVM_NO_DEAD_STRIP=ON \
  -DCMAKE_C_COMPILER="$(xcrun -f clang)" -DCMAKE_CXX_COMPILER="$(xcrun -f clang++)" \
  -DCROSS_TOOLCHAIN_FLAGS_NATIVE="-DCMAKE_C_COMPILER=$(xcrun -f clang);-DCMAKE_CXX_COMPILER=$(xcrun -f clang++)" \
  -DCMAKE_C_FLAGS="$FLAGS" -DCMAKE_CXX_FLAGS="$FLAGS" \
  -DCMAKE_EXE_LINKER_FLAGS="$LINK" -DCMAKE_SHARED_LINKER_FLAGS="$LINK" \
  -DLLVM_ENABLE_PROJECTS="clang;lld" \
  -DLLVM_TARGETS_TO_BUILD=WebAssembly \
  -DLLVM_DEFAULT_TARGET_TRIPLE=wasm32-wasip1 \
  -DLLVM_ENABLE_ASSERTIONS=OFF -DLLVM_ENABLE_BACKTRACES=OFF -DLLVM_ENABLE_PLUGINS=OFF -DCLANG_PLUGIN_SUPPORT=OFF \
  -DLLVM_ENABLE_ZLIB=OFF -DLLVM_ENABLE_ZSTD=OFF -DLLVM_ENABLE_LIBXML2=OFF -DLLVM_ENABLE_LIBEDIT=OFF \
  -DLLVM_ENABLE_TERMINFO=OFF -DLLVM_ENABLE_LIBPFM=OFF -DLLVM_ENABLE_PER_TARGET_RUNTIME_DIR=OFF \
  -DLLVM_ENABLE_CRASH_OVERRIDES=OFF \
  -DCLANG_ENABLE_STATIC_ANALYZER=OFF -DCLANG_ENABLE_ARCMT=OFF -DCLANG_ENABLE_OBJC_REWRITER=OFF \
  -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_EXAMPLES=OFF -DLLVM_INCLUDE_BENCHMARKS=OFF -DLLVM_INCLUDE_DOCS=OFF \
  -DCLANG_INCLUDE_TESTS=OFF -DCLANG_INCLUDE_DOCS=OFF -DLLVM_BUILD_TOOLS=OFF -DLLVM_BUILD_UTILS=OFF \
  -DLLVM_ENABLE_BINDINGS=OFF -DLLVM_ENABLE_OCAMLDOC=OFF -DCLANG_TOOL_C_INDEX_TEST_BUILD=OFF \
  -DCMAKE_MACOSX_BUNDLE=OFF -DLLVM_TOOL_LLVM_DRIVER_BUILD=OFF
